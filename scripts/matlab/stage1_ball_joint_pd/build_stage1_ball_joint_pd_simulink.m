% Build and open the Stage1 uniform ball-joint PD Simulink model.

init_stage1_ball_joint_pd_workspace;

model_name = "stage1_ball_joint_pd_uniform";
model_file = fullfile(script_dir, model_name + ".slx");

if bdIsLoaded(model_name)
    close_system(model_name, 0);
end

if isfile(model_file)
    load_system(model_file);
    Simulink.BlockDiagram.deleteContents(model_name);
else
    new_system(model_name);
end
load_system("simulink");

set_param(model_name, ...
    "Solver", "FixedStepDiscrete", ...
    "FixedStep", "dt_sim", ...
    "StopTime", "stop_time_s", ...
    "SignalLogging", "on");

init_callback = ...
    "evalin('base', 'run(fullfile(fileparts(get_param(''stage1_ball_joint_pd_uniform'', ''FileName'')), ''init_stage1_ball_joint_pd_workspace.m''))')";
set_param(model_name, ...
    "PostLoadFcn", init_callback, ...
    "InitFcn", init_callback);

add_model_blocks(model_name);
save_system(model_name, model_file);
open_system(model_name);

fprintf("Built and opened Simulink model: %s\n", model_file);
fprintf("Workspace source trace: %s\n", string(trace_csv_path));
fprintf("Default uniform gain: Kp = %.3g, Kd = %.3g, tau_v = %.3g, tau_max = %.3g, qdot_max = %.3g\n", ...
    Kp, Kd, tau_v, tau_max, qdot_max);

function add_model_blocks(model_name)
    add_inputs(model_name);
    add_plant(model_name);
    add_outputs(model_name);
    add_joint_display_subsystems(model_name);
    style_blocks(model_name);
    connect_blocks(model_name);
end

