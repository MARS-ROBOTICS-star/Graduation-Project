function add_to_workspace(model_name, variable_name, position)
    add_block("simulink/Sinks/To Workspace", model_name + "/" + variable_name, ...
        "VariableName", variable_name, ...
        "SaveFormat", "Timeseries", ...
        "MaxDataPoints", "inf", ...
        "Position", position);
end

function add_goto(model_name, block_name, tag, position)
    add_block("simulink/Signal Routing/Goto", model_name + "/" + block_name, ...
        "GotoTag", tag, ...
        "TagVisibility", "global", ...
        "Position", position);
end

function add_joint_display_subsystems(model_name)
    joint_labels = [
        "J1 spm1 z yaw", ...
        "J2 spm1 y pitch", ...
        "J3 spm1 x roll", ...
        "J4 spm2 z yaw", ...
        "J5 spm2 y pitch", ...
        "J6 spm2 x roll" ...
    ];
    block_names = [
        "J1_spm1_z_scopes", ...
        "J2_spm1_y_scopes", ...
        "J3_spm1_x_scopes", ...
        "J4_spm2_z_scopes", ...
        "J5_spm2_y_scopes", ...
        "J6_spm2_x_scopes" ...
    ];

    x0 = 60;
    y0 = 700;
    dx = 740;
    dy = 285;
    width = 650;
    height = 205;

    for joint_index = 1:6
        row = floor((joint_index - 1) / 3);
        col = mod(joint_index - 1, 3);
        position = [x0 + col * dx, y0 + row * dy, x0 + col * dx + width, y0 + row * dy + height];
        subsystem_path = model_name + "/" + block_names(joint_index);

        add_block("simulink/Ports & Subsystems/Subsystem", subsystem_path, ...
            "Position", position, ...
            "BackgroundColor", "lightBlue", ...
            "FontSize", 15, ...
            "FontWeight", "bold");
        Simulink.SubSystem.deleteContents(subsystem_path);
        set_param(subsystem_path, "NamePlacement", "normal");
        build_joint_display_subsystem(subsystem_path, joint_index, joint_labels(joint_index));
    end
end

function build_joint_display_subsystem(subsystem_path, joint_index, ~)

    angle_scope = subsystem_path + "/Angle rad";
    velocity_scope = subsystem_path + "/Velocity radps";
    torque_scope = subsystem_path + "/Torque Nm";

    add_block("simulink/Sinks/Scope", angle_scope, ...
        "NumInputPorts", "5", ...
        "Position", [760, 55, 1060, 190], ...
        "FontSize", 15);
    style_scope(angle_scope, "Angle response", "Angle (rad)", [120, 140, 980, 560]);
    add_block("simulink/Sinks/Scope", velocity_scope, ...
        "NumInputPorts", "4", ...
        "Position", [760, 245, 1060, 380], ...
        "FontSize", 15);
    style_scope(velocity_scope, "Velocity response", "Velocity (rad/s)", [160, 170, 980, 560]);
    add_block("simulink/Sinks/Scope", torque_scope, ...
        "NumInputPorts", "1", ...
        "Position", [760, 435, 1060, 540], ...
        "FontSize", 15);
    style_scope(torque_scope, "Torque command", "Torque (N*m)", [200, 200, 980, 520]);

    angle_tags = ["q_desired_vec", "q_target_old_vec", "q_actual_old_vec", "q_target_new_vec", "q_sim_new_vec"];
    angle_names = ["q_desired", "q_target_old", "q_actual_old", "q_target_new", "q_sim_new"];
    angle_legend_names = ["q desired", "old target", "old actual", "new target", "new sim"];
    for signal_index = 1:numel(angle_tags)
        add_from_demux(subsystem_path, angle_names(signal_index), angle_tags(signal_index), ...
            [55, 75 + (signal_index - 1) * 42, 205, 107 + (signal_index - 1) * 42], ...
            [290, 75 + (signal_index - 1) * 42, 322, 107 + (signal_index - 1) * 42]);
        add_named_line(subsystem_path, "Demux_" + angle_names(signal_index) + "/" + string(joint_index), ...
            "Angle rad/" + string(signal_index), angle_legend_names(signal_index));
    end

    velocity_tags = ["qdot_actual_old_vec", "qdot_cmd_old_vec", "qdot_sim_new_vec", "qdot_alloc_new_vec"];
    velocity_names = ["qdot_actual_old", "qdot_cmd_old", "qdot_sim_new", "qdot_alloc_new"];
    velocity_legend_names = ["old qdot actual", "old qdot cmd", "new qdot sim", "new qdot alloc"];
    for signal_index = 1:numel(velocity_tags)
        add_from_demux(subsystem_path, velocity_names(signal_index), velocity_tags(signal_index), ...
            [55, 270 + (signal_index - 1) * 42, 205, 302 + (signal_index - 1) * 42], ...
            [290, 270 + (signal_index - 1) * 42, 322, 302 + (signal_index - 1) * 42]);
        add_named_line(subsystem_path, "Demux_" + velocity_names(signal_index) + "/" + string(joint_index), ...
            "Velocity radps/" + string(signal_index), velocity_legend_names(signal_index));
    end

    add_from_demux(subsystem_path, "tau_sim_new", "tau_sim_new_vec", ...
        [55, 470, 205, 502], [290, 470, 322, 502]);
    add_named_line(subsystem_path, "Demux_tau_sim_new/" + string(joint_index), "Torque Nm/1", "new tau");

end

function demux_path = add_from_demux(subsystem_path, signal_name, tag, from_position, demux_position)
    from_path = subsystem_path + "/From_" + signal_name;
    demux_path = subsystem_path + "/Demux_" + signal_name;
    add_block("simulink/Signal Routing/From", from_path, ...
        "GotoTag", tag, ...
        "Position", from_position, ...
        "FontSize", 13);
    add_block("simulink/Signal Routing/Demux", demux_path, ...
        "Outputs", "6", ...
        "Position", demux_position, ...
        "FontSize", 13);
    add_line(subsystem_path, "From_" + signal_name + "/1", "Demux_" + signal_name + "/1", "autorouting", "on");
end

function add_named_line(system_path, source_port, destination_port, signal_name)
    line_handle = add_line(system_path, source_port, destination_port, "autorouting", "on");
    try
        set_param(line_handle, "Name", signal_name);
        set_param(line_handle, "FontSize", 13);
    catch
    end
end

function style_scope(scope_path, title_text, y_label, window_position)
    set_param(scope_path, ...
        "BackgroundColor", "white", ...
        "ForegroundColor", "black", ...
        "FontName", "Arial", ...
        "FontSize", 15, ...
        "ShowLegend", "on", ...
        "ShowGrid", "on");
    try
        scope_config = get_param(scope_path, "ScopeConfiguration");
        scope_config.Title = title_text;
        scope_config.YLabel = y_label;
        scope_config.ShowLegend = true;
        scope_config.ShowGrid = true;
        scope_config.MaximizeAxes = "On";
        scope_config.MinimizeControls = true;
        scope_config.AxesScaling = "Auto";
        scope_config.TimeAxisLabels = "Bottom";
        scope_config.ShowTimeAxisLabel = true;
        scope_config.PreserveColorsForCopyToClipboard = false;
        scope_config.Position = window_position;
    catch
    end
end

function style_blocks(model_name)
    all_blocks = find_system(model_name, "FindAll", "on", "Type", "Block");
    for block = reshape(all_blocks, 1, [])
        try
            set_param(block, "FontName", "Arial");
            set_param(block, "FontSize", 14);
        catch
        end
    end

    try
        set_param(model_name, "Location", [60, 60, 1880, 1040]);
        set_param(model_name, "ZoomFactor", "FitSystem");
    catch
    end

    color_blocks(model_name, ["q_desired", "q_target_old", "q_actual_old", "qdot_actual_old", "qdot_cmd_old"], "lightGreen");
    color_blocks(model_name, ["Clamp q target", "q error", "Kp", "Kd", "PD torque", "Torque saturation"], "lightBlue");
    color_blocks(model_name, ["qdot integrator", "qdot saturation", "q integrator", "q saturation", "qdot allocator LPF"], "yellow");
    color_blocks(model_name, ["q_target_new", "q_sim_new", "qdot_sim_new", "qdot_alloc_new", "tau_sim_new", "tau_saturation_flag_new"], "white");
end

function color_blocks(model_name, block_names, color)
    for block_name = block_names
        block_path = model_name + "/" + block_name;
        if getSimulinkBlockHandle(block_path) ~= -1
            try
                set_param(block_path, "BackgroundColor", color);
            catch
            end
        end
    end
end

